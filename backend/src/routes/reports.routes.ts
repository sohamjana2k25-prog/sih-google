import { Router, Request, Response } from 'express';
import PDFDocument from 'pdfkit';
import db from '../database/db.js';
import { ComplianceEngine } from '../compliance/complianceEngine.js';

const router = Router();

// GET /api/reports/institution/:id/pdf (Downloadable PDF Compliance Report)
router.get('/institution/:id/pdf', (req: Request, res: Response) => {
  const institution = db.prepare(`SELECT * FROM institutions WHERE id = ?`).get(req.params.id) as any;
  if (!institution) {
    return res.status(404).json({ error: 'Institution not found' });
  }

  const compliance = ComplianceEngine.evaluateInstitutionCompliance(req.params.id);
  const alerts = db.prepare(`
    SELECT * FROM compliance_alerts WHERE institution_id = ? AND status = 'OPEN'
  `).all(req.params.id) as any[];

  const doc = new PDFDocument({ margin: 40, size: 'A4' });

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="AICTE_Compliance_Report_${institution.aicte_id}.pdf"`
  );

  doc.pipe(res);

  // Header
  doc
    .fontSize(18)
    .font('Helvetica-Bold')
    .text('ALL INDIA COUNCIL FOR TECHNICAL EDUCATION (AICTE)', { align: 'center' });
  doc
    .fontSize(12)
    .font('Helvetica')
    .text('APAAR-Sentinel Regulatory Compliance & Admission Audit Report', { align: 'center' });
  doc.moveDown(0.5);
  doc.strokeColor('#CBD5E1').lineWidth(1).moveTo(40, doc.y).lineTo(550, doc.y).stroke();
  doc.moveDown(1);

  // Metadata
  doc.fontSize(10).font('Helvetica-Bold').text(`Institution Name: `, { continued: true }).font('Helvetica').text(institution.name);
  doc.fontSize(10).font('Helvetica-Bold').text(`AICTE Institution ID: `, { continued: true }).font('Helvetica').text(institution.aicte_id);
  doc.fontSize(10).font('Helvetica-Bold').text(`State / District: `, { continued: true }).font('Helvetica').text(`${institution.state}, ${institution.district}`);
  doc.fontSize(10).font('Helvetica-Bold').text(`Institutional Category: `, { continued: true }).font('Helvetica').text(institution.type);
  doc.fontSize(10).font('Helvetica-Bold').text(`Academic Session: `, { continued: true }).font('Helvetica').text(compliance.academicSession);
  doc.fontSize(10).font('Helvetica-Bold').text(`Report Generated At: `, { continued: true }).font('Helvetica').text(new Date().toUTCString());
  doc.moveDown(1);

  // Summary Metrics Table
  doc.fontSize(12).font('Helvetica-Bold').text('1. Institutional Intake Summary');
  doc.moveDown(0.5);
  doc.fontSize(10).font('Helvetica').text(`Total Approved Sanctioned Intake: ${compliance.totalApprovedIntake} seats`);
  doc.fontSize(10).font('Helvetica').text(`Total Active Reported Admissions: ${compliance.totalActiveEnrolment} students`);
  doc.fontSize(10).font('Helvetica').text(`Overall Capacity Utilization: ${compliance.overallUtilization}%`);
  doc.fontSize(10).font('Helvetica').text(`Compliance Status: ${compliance.hasViolations ? 'VIOLATIONS DETECTED' : 'FULLY COMPLIANT'}`);
  doc.moveDown(1);

  // Programme Breakdown
  doc.fontSize(12).font('Helvetica-Bold').text('2. Programme-Wise Sanctioned vs Actual Enrolment');
  doc.moveDown(0.5);

  for (const prog of compliance.programmes) {
    doc.fontSize(10).font('Helvetica-Bold').text(`${prog.programmeName} (${prog.programmeCode}) - ${prog.degree}`);
    doc
      .fontSize(9)
      .font('Helvetica')
      .text(
        `Approved: ${prog.approvedIntake} | Actual Admissions: ${prog.regularAdmissions} (Regular: ${prog.regularAdmissions}, NRI: ${prog.nriAdmissions}, Supernumerary: ${prog.supernumeraryAdmissions}) | Utilization: ${prog.utilizationPercentage}% | Status: ${prog.complianceStatus}`
      );
    if (prog.excessAdmissions > 0) {
      doc.fillColor('#DC2626').text(`[CRITICAL ALERT] Intake Capacity Exceeded by ${prog.excessAdmissions} seat(s). Formal AICTE inquiry triggered.`).fillColor('#000000');
    }
    doc.moveDown(0.4);
  }

  doc.moveDown(0.8);

  // Active Alerts
  doc.fontSize(12).font('Helvetica-Bold').text('3. Active Regulatory Compliance Alerts');
  doc.moveDown(0.5);

  if (alerts.length === 0) {
    doc.fontSize(9).font('Helvetica').text('No open compliance or intake excess alerts registered for this institution.');
  } else {
    for (const a of alerts) {
      doc.fontSize(10).font('Helvetica-Bold').text(`[${a.severity}] ${a.title}`);
      doc.fontSize(9).font('Helvetica').text(`Description: ${a.description}`);
      doc.fontSize(8).font('Helvetica').text(`Logged on: ${new Date(a.created_at).toLocaleDateString()}`);
      doc.moveDown(0.4);
    }
  }

  doc.moveDown(1.5);
  doc.fontSize(8).font('Helvetica').text('This document is electronically generated by the AICTE APAAR-Sentinel Regulatory Intelligence Platform. Valid for regulatory review.', { align: 'center' });

  doc.end();
});

// GET /api/reports/institution/:id/csv (Downloadable CSV)
router.get('/institution/:id/csv', (req: Request, res: Response) => {
  const institution = db.prepare(`SELECT * FROM institutions WHERE id = ?`).get(req.params.id) as any;
  if (!institution) {
    return res.status(404).json({ error: 'Institution not found' });
  }

  const compliance = ComplianceEngine.evaluateInstitutionCompliance(req.params.id);

  let csv = 'Programme Name,Programme Code,Degree,Approved Intake,Actual Enrolment,Utilization %,Remaining Capacity,Excess Seats,Compliance Status\n';

  for (const p of compliance.programmes) {
    csv += `"${p.programmeName}","${p.programmeCode}","${p.degree}",${p.approvedIntake},${p.totalActiveEnrolment},${p.utilizationPercentage}%,${p.remainingCapacity},${p.excessAdmissions},"${p.complianceStatus}"\n`;
  }

  res.setHeader('Content-Type', 'text/csv');
  res.setHeader('Content-Disposition', `attachment; filename="Intake_Report_${institution.aicte_id}.csv"`);
  return res.send(csv);
});

// GET /api/reports/aicte/summary
router.get('/aicte/summary', (req: Request, res: Response) => {
  const summary = db.prepare(`
    SELECT i.aicte_id, i.name as institution_name, i.state, i.type,
           SUM(p.approved_intake) as total_sanctioned,
           COUNT(e.id) as total_admissions,
           ROUND(COUNT(e.id) * 100.0 / SUM(p.approved_intake), 1) as utilization_pct,
           i.risk_score
    FROM institutions i
    JOIN programmes p ON i.id = p.institution_id
    LEFT JOIN enrolments e ON p.id = e.programme_id AND e.enrolment_status = 'ACTIVE'
    GROUP BY i.id
    ORDER BY i.risk_score DESC
  `).all();

  return res.json({ summary });
});

export default router;
